type ProjectRow = {
	id: number;
	slug: string;
	title: string;
	prompt: string;
	findings_md: string;
	open_questions: string;
	hidden_at: number | null;
};

type WorkerState = {
	started: boolean;
	/** Set at SIGTERM. No further run is started. */
	stopping: boolean;
	active: Set<number>;
	aborts: Map<number, AbortController>;
	timer?: ReturnType<typeof setInterval>;
};

const holder = globalThis as unknown as { __osWorker?: WorkerState };
const state: WorkerState = (holder.__osWorker ??= {
	started: false,
	stopping: false,
	active: new Set(),
	aborts: new Map()
});

/** Asked when a new donation arrives on a project whose list of questions is empty. */
const REVIEW_QUESTION =
	'What important aspects of the prompt have not yet been covered by the findings so far?';

const AI_NOTE =
	'This text was generated by an AI model and has not been independently reviewed.';

export function startWorker() {
	if (state.started) return;
	state.started = true;
	// Work that was interrupted by a restart is resumed from the last finished run.
	run(`UPDATE donations SET status = 'queued' WHERE status = 'running'`);
	state.timer = setInterval(kick, 3000);
	state.timer.unref?.();
	// The development server handles its own signals.
	if (!dev) {
		process.on('SIGTERM', drain);
		process.on('SIGINT', drain);
	}
	kick();
}

/** Runs in progress at shutdown are given this long to finish. Railway ends the process after 120 seconds. */
const DRAIN_MS = 100_000;

/**
 * Railway sends SIGTERM before every deployment, and starts the new one only once this process has
 * ended. No further run is started, and those in progress are allowed to finish. Live connections are
 * then closed, and the process ends when the server has answered its last request. After DRAIN_MS it
 * ends regardless, and any run still in progress is resumed at the next start, as after a crash. A
 * second signal ends the process at once.
 */
function drain() {
	if (state.stopping) process.exit(0);
	state.stopping = true;
	clearInterval(state.timer);
	setTimeout(() => {
		console.error('The server was stopped with a run in progress. It will be resumed at the next start.');
		process.exit(0);
	}, DRAIN_MS).unref();
	// adapter-node emits this once its server has closed and every request has been answered.
	const served = new Promise((resolve) => process.once('sveltekit:shutdown', resolve));
	void (async () => {
		while (state.active.size > 0) await new Promise((resolve) => setTimeout(resolve, 250));
		closeStreams();
		await served;
		process.exit(0);
	})();
}

export function kick() {
	if (state.stopping) return;
	// A round that has closed turns its leading pledges into donations, which are then found below.
	try {
		settleDue();
	} catch (err) {
		console.error('Rounds could not be examined:', scrub(String(err)));
	}
	const open = all<{ project_id: number }>(
		`SELECT project_id, MIN(id) AS first FROM donations
		WHERE status IN ('queued','running') GROUP BY project_id ORDER BY first`
	);
	for (const { project_id: projectId } of open) {
		if (state.active.has(projectId)) continue;
		if (state.active.size >= config.maxActiveProjects) break;
		state.active.add(projectId);
		processProject(projectId)
			.catch((err) => console.error('Worker error:', scrub(String(err))))
			.finally(() => {
				state.active.delete(projectId);
				publishEnd(projectId);
			});
	}
}

/** Ends a donation at once. Nothing further is spent from it. */
export function stopDonation(donationId: number, reason: string, status: 'stopped' | 'failed' = 'stopped') {
	run(
		`UPDATE donations SET status = ?, end_reason = ?, finished_at = ?
		WHERE id = ? AND status IN ('queued','running')`,
		status,
		reason,
		Date.now(),
		donationId
	);
	state.aborts.get(donationId)?.abort();
}

/** Called when a key is removed, so that nothing further is attempted with it. */
export function stopDonationsForUser(userId: number, reason: string) {
	const open = all<{ id: number }>(
		`SELECT id FROM donations WHERE user_id = ? AND status IN ('queued','running')`,
		userId
	);
	for (const { id } of open) stopDonation(id, reason, 'failed');
}

function finish(donationId: number, status: 'completed' | 'failed', reason: string) {
	run(
		`UPDATE donations SET status = ?, end_reason = ?, finished_at = ?
		WHERE id = ? AND status IN ('queued','running')`,
		status,
		reason,
		Date.now(),
		donationId
	);
}

async function processProject(projectId: number) {
	for (;;) {
		// A donation left open here is resumed at the next start.
		if (state.stopping) return;
		const donation = get<DonationRow>(
			`SELECT * FROM donations WHERE project_id = ? AND status IN ('queued','running')
			ORDER BY id LIMIT 1`,
			projectId
		);
		if (!donation) return;
		run(`UPDATE donations SET status = 'running' WHERE id = ? AND status = 'queued'`, donation.id);
		const controller = new AbortController();
		state.aborts.set(donation.id, controller);
		try {
			await runOnce(donation, controller.signal);
		} catch (err) {
			if (!controller.signal.aborted) {
				const reason = describeFailure(err);
				console.error(`Donation ${donation.id} failed:`, scrub(String(err)));
				finish(donation.id, 'failed', reason);
			}
		} finally {
			state.aborts.delete(donation.id);
			if (currentRun(projectId)) publishEnd(projectId);
		}
	}
}

function describeFailure(err: unknown): string {
	if (err instanceof TypeError) return 'OpenRouter could not be reached after several attempts.';
	if (err instanceof OpenRouterError) {
		if (err.partial) {
			return 'The model stopped part way through. That attempt may have been charged, so its maximum cost has been counted against this donation.';
		}
		switch (err.status) {
			case 401:
				return 'The key was rejected by OpenRouter. It may have been disabled or deleted.';
			case 402:
				return 'OpenRouter declined the charge. No credit remains on the key or the account, or too little for a request of this size.';
			case 403:
				return 'The request was declined by OpenRouter or the model provider.';
			case 400:
			case 404:
				return 'The request was not accepted for this model.';
			default:
				return 'The model remained unavailable after several attempts.';
		}
	}
	return 'The run could not be completed because of an internal error.';
}

const RETRYABLE = new Set([408, 429, 500, 502, 503, 504]);

async function withRetry<T>(
	signal: AbortSignal,
	attempt: (retrying: boolean) => Promise<T>,
	tries = 3
): Promise<T> {
	for (let i = 0; ; i++) {
		try {
			return await attempt(i > 0);
		} catch (err) {
			if (signal.aborted) throw err;
			// Text has arrived, so the attempt may have been paid for. It is not paid for twice.
			if (err instanceof OpenRouterError && err.partial) throw err;
			const status = err instanceof OpenRouterError ? err.status : 0;
			const network = err instanceof TypeError;
			// A 402 that says when to retry means too much is held for requests in progress, not that
			// the key is empty. Low balances meet this between a report and the edit that follows it.
			const heldBack = status === 402 && err instanceof OpenRouterError && Boolean(err.retryAfterMs);
			if (i >= tries - 1 || !(RETRYABLE.has(status) || network || heldBack)) throw err;
			const wait =
				err instanceof OpenRouterError && err.retryAfterMs
					? Math.min(err.retryAfterMs, 30_000)
					: 2000 * 2 ** i;
			await new Promise((resolve) => setTimeout(resolve, wait));
		}
	}
}

/**
 * Adjusts what has been spent from a donation. The maximum an attempt could cost is counted before
 * it starts and corrected afterwards, so a crash or a broken stream can never go unrecorded.
 */
function charge(donationId: number, micro: number) {
	run(
		`UPDATE donations SET spent_micro = MAX(0, spent_micro + ?) WHERE id = ?`,
		micro,
		donationId
	);
}

async function meteredChat(
	donationId: number,
	maximum: number,
	signal: AbortSignal,
	attempt: (retrying: boolean) => Promise<ChatResult>
): Promise<ChatResult> {
	return withRetry(signal, async (retrying) => {
		charge(donationId, maximum);
		try {
			const result = await attempt(retrying);
			charge(donationId, result.costMicro - maximum);
			return result;
		} catch (err) {
			// With no text received, nothing was generated. Otherwise the maximum stands.
			if (!(err instanceof OpenRouterError && err.partial)) charge(donationId, -maximum);
			throw err;
		}
	});
}

/** Control characters cannot be stored by git, and line breaks could forge the fields of a record. */
function oneLine(text: string): string {
	return text.replace(/[\u0000-\u001F\u007F]+/g, ' ').replace(/\s+/g, ' ').trim();
}

function pad(seq: number) {
	return String(seq).padStart(4, '0');
}

function bufferedDeltas(projectId: number) {
	let pending = '';
	let timer: ReturnType<typeof setTimeout> | undefined;
	const flush = () => {
		timer = undefined;
		if (pending) publishDelta(projectId, pending);
		pending = '';
	};
	return {
		push(text: string) {
			pending += text;
			timer ??= setTimeout(flush, 50);
		},
		flush() {
			if (timer) clearTimeout(timer);
			flush();
		}
	};
}

async function runOnce(donation: DonationRow, signal: AbortSignal) {
	const project = get<ProjectRow>(
		`SELECT id, slug, title, prompt, findings_md, open_questions, hidden_at FROM projects WHERE id = ?`,
		donation.project_id
	)!;
	if (project.hidden_at) return finish(donation.id, 'failed', 'The project was removed by the operator of this site.');
	const donor = get<{ handle: string; github_id: string }>(
		'SELECT handle, github_id FROM users WHERE id = ?',
		donation.user_id
	)!;

	const key = readKey(donation.user_id);
	if (!key) return finish(donation.id, 'failed', 'The OpenRouter key has been removed.');

	const model = await withRetry(signal, () => findModel(donation.model));
	if (!model) return finish(donation.id, 'failed', 'The model is no longer offered by OpenRouter.');

	const remaining = donation.amount_micro - donation.spent_micro;
	if (donation.run_count >= MAX_RUNS_PER_DONATION) {
		return finish(donation.id, 'completed', `The limit of ${MAX_RUNS_PER_DONATION} runs per donation was reached.`);
	}
	if (remaining < minimumRunMicro(model.pricing)) {
		return finish(donation.id, 'completed', 'The donation has been spent.');
	}

	// A donation that came from a round was pledged towards one question, which is asked before any other.
	const proposal = donation.proposal_id
		? get<{ id: number; question: string; status: string; handle: string }>(
				`SELECT o.id, o.question, o.status, u.handle FROM proposals o JOIN users u ON u.id = o.user_id WHERE o.id = ?`,
				donation.proposal_id
			)
		: undefined;
	if (proposal?.status === 'removed') {
		return finish(donation.id, 'failed', 'The question was removed by the operator of this site.');
	}
	// Set until that question has been put, which is on the first run of the first of its donations.
	const directed =
		proposal &&
		!get<{ id: number }>(
			`SELECT r.id FROM runs r JOIN donations d ON d.id = r.donation_id WHERE d.proposal_id = ? LIMIT 1`,
			proposal.id
		)
			? proposal
			: undefined;

	const questions = JSON.parse(project.open_questions) as string[];
	const lastSeq =
		get<{ n: number }>('SELECT COALESCE(MAX(seq), 0) AS n FROM runs WHERE project_id = ?', project.id)?.n ?? 0;
	// A donation's later runs stop when the list runs out. A new donation may always ask what is missing.
	if (!directed && project.findings_md && questions.length === 0 && donation.run_count > 0) {
		return finish(donation.id, 'completed', 'No open questions remain on this project.');
	}
	const question = oneLine(
		directed ? directed.question : (questions[0] ?? (project.findings_md ? REVIEW_QUESTION : project.prompt))
	);

	const info = await withRetry(signal, () => checkKey(key));
	updateKeyInfo(donation.user_id, info);
	if (info.remainingMicro !== null && info.remainingMicro <= 0) {
		return finish(donation.id, 'failed', 'The spending limit on the key has been reached.');
	}

	const seq = lastSeq + 1;
	const budget = Math.min(
		runBudgetMicro(donation.amount_micro, remaining),
		info.remainingMicro ?? Number.MAX_SAFE_INTEGER
	);

	publishRun(project.id, {
		seq,
		phase: 'searching',
		question,
		modelName: model.name,
		handle: donor.handle,
		text: ''
	});

	const knownSources = extractLinks(project.findings_md);
	const system = researchSystem({ prompt: project.prompt, findings: project.findings_md, knownSources });
	const user = `Question: ${question}`;
	const inputEstimate = estimateTokens(system + user) + SEARCH_RESULT_TOKENS;
	const researchTokens = affordableOutputTokens(
		Math.floor(budget * 0.7),
		inputEstimate,
		model.pricing,
		MAX_RESEARCH_TOKENS,
		WEB_SEARCH_MICRO
	);
	if (researchTokens === 0) {
		return finish(donation.id, 'completed', 'The remaining amount was too small for a further run.');
	}

	const deltas = bufferedDeltas(project.id);
	let first = true;
	const researchMaximum =
		costMicro(inputEstimate, researchTokens, model.pricing) + WEB_SEARCH_MICRO;
	const research = await meteredChat(donation.id, researchMaximum, signal, (retrying) => {
		if (retrying) {
			publishRun(project.id, { seq, phase: 'searching', question, modelName: model.name, handle: donor.handle, text: '' });
		}
		first = true;
		return chat({
			key,
			model: model.id,
			pricing: model.pricing,
			lowEffort: model.lowEffort,
			system,
			user,
			maxTokens: researchTokens,
			web: true,
			signal,
			onDelta: (text) => {
				if (first) {
					first = false;
					publishPhase(project.id, 'writing');
				}
				deltas.push(text);
			}
		});
	});
	deltas.flush();

	if (!research.text.trim()) {
		return finish(
			donation.id,
			'failed',
			'The model returned no text. Its allowance may have been used up by its own reasoning.'
		);
	}

	let cost = research.costMicro;
	let inputTokens = research.inputTokens;
	let outputTokens = research.outputTokens;

	const nothingNew = isNoNewFindings(research.text);
	// A report that reached its length limit is kept, and is marked so that it is not read as complete.
	const body =
		research.finishReason === 'length'
			? `${research.text.trimEnd()}\n\n*This report reached the length allowed for one run, and ends before the model had finished.*`
			: research.text;
	const report = nothingNew
		? 'No new findings were reported for this question.\n'
		: withSources(body, research.sources);

	let findings = project.findings_md;
	// A question that was pledged towards did not come from the list, so nothing is taken off it.
	let nextQuestions = directed ? questions : questions.slice(1);

	if (!nothingNew) {
		publishPhase(project.id, 'editing');
		// The report has been paid for, so it is kept even if the donation is stopped at this point.
		const edited = await edit({
			project,
			donationId: donation.id,
			report,
			direction: proposal?.question,
			key,
			model,
			budget: budget - cost,
			signal
		});
		if (edited.result) {
			cost += edited.result.costMicro;
			inputTokens += edited.result.inputTokens;
			outputTokens += edited.result.outputTokens;
		}
		if (edited.parsed) {
			findings = edited.parsed.findings;
			nextQuestions = edited.parsed.questions;
		} else {
			// The report is never lost: if the edit fails, it is appended as it stands, up to the limit in
			// appendReport, and it is always kept in its own run. The list of questions was not revised,
			// so the project must not be left with nothing to ask.
			findings = appendReport(findings, report);
			if (nextQuestions.length === 0) nextQuestions = [question];
		}
	}

	const reportHtml = renderMarkdown(report);
	const findingsHtml = renderMarkdown(findings);
	const finishedAt = Date.now();
	const name = `runs/${pad(seq)}`;
	const header = `# Run ${seq}

Question: ${question}
Model: ${model.id}
${directed ? `Proposed by: @${directed.handle}\n` : ''}Funded by: @${donor.handle}
Tokens: ${inputTokens} in, ${outputTokens} out
Cost: $${(cost / 1_000_000).toFixed(6)} USD
Completed: ${new Date(finishedAt).toISOString()}

---

`;
	const files: Record<string, string> = {
		[`${name}.md`]: header + report,
		[`${name}.html`]: standaloneHtml(`Run ${seq}: ${question}`, reportHtml, AI_NOTE),
		'findings.md': findings,
		'findings.html': standaloneHtml(project.title, findingsHtml, AI_NOTE),
		'open-questions.md': nextQuestions.length
			? `# Open questions\n\n${nextQuestions.map((q) => `- ${q}`).join('\n')}\n`
			: '# Open questions\n\nNone are listed at present.\n'
	};
	const subject = question.length > 60 ? `${question.slice(0, 59).trimEnd()}…` : question;
	if (signal.aborted && !findings) return;
	// A project may have been removed while this run was being written. Nothing further is published.
	const stillPublic = get<{ hidden_at: number | null }>('SELECT hidden_at FROM projects WHERE id = ?', project.id);
	if (stillPublic?.hidden_at) return;
	const sha = await commitFiles(
		project.slug,
		files,
		`Run ${seq}: ${subject}

Question: ${question}
${directed ? `Proposed-by: @${directed.handle}\n` : ''}Funded-by: @${donor.handle}
Model: ${model.id}
Input-tokens: ${inputTokens}
Output-tokens: ${outputTokens}
Cost-usd: ${(cost / 1_000_000).toFixed(6)}
`,
		{ name: `@${donor.handle}`, email: `${donor.github_id}@github.openresearch.invalid` }
	);

	const sources: Source[] = research.sources;
	tx(() => {
		run(
			`INSERT INTO runs (project_id, donation_id, user_id, seq, model, model_name, question, status,
				report_md, report_html, sources, input_tokens, output_tokens, cost_micro, commit_sha, started_at, finished_at)
			VALUES (?, ?, ?, ?, ?, ?, ?, 'completed', ?, ?, ?, ?, ?, ?, ?, ?, ?)`,
			project.id,
			donation.id,
			donation.user_id,
			seq,
			model.id,
			model.name,
			question,
			report,
			reportHtml,
			JSON.stringify(sources),
			inputTokens,
			outputTokens,
			cost,
			sha,
			finishedAt,
			finishedAt
		);
		run(
			`UPDATE projects SET findings_md = ?, findings_html = ?, open_questions = ? WHERE id = ?`,
			findings,
			findingsHtml,
			JSON.stringify(nextQuestions),
			project.id
		);
		run(`UPDATE donations SET run_count = run_count + 1 WHERE id = ?`, donation.id);
	});
	publishEnd(project.id);
}

async function edit(input: {
	project: ProjectRow;
	donationId: number;
	report: string;
	/** The question that donors chose in a round, where the donation came from one. */
	direction?: string;
	key: string;
	model: Model;
	budget: number;
	signal: AbortSignal;
}): Promise<{ result?: ChatResult; parsed: ReturnType<typeof parseEdited> }> {
	if (input.signal.aborted) return { parsed: null };
	const system = editorSystem({
		prompt: input.project.prompt,
		findings: input.project.findings_md,
		direction: input.direction
	});
	const inputTokens = estimateTokens(system + input.report);
	const tokens = affordableOutputTokens(
		input.budget,
		inputTokens,
		input.model.pricing,
		MAX_EDITOR_TOKENS
	);
	if (tokens === 0) return { parsed: null };
	try {
		const maximum = costMicro(inputTokens, tokens, input.model.pricing);
		const result = await meteredChat(input.donationId, maximum, input.signal, () =>
			chat({
				key: input.key,
				model: input.model.id,
				pricing: input.model.pricing,
				lowEffort: input.model.lowEffort,
				system,
				user: input.report,
				maxTokens: tokens,
				signal: input.signal
			})
		);
		return { result, parsed: parseEdited(result.text) };
	} catch (err) {
		if (!input.signal.aborted) console.error('Edit step failed:', scrub(String(err)));
		return { parsed: null };
	}
}
