	<div class="prose">
		<p>OpenResearch is a public board of research prompts. Any prompt of up to 250 words may be listed by anyone with a GitHub account, and a public repository is created for it. Research on that prompt is then paid for by whoever chooses to donate towards it.</p>

		<h2>How a donation is made</h2>
		<p>An OpenRouter API key is added to the account, and an amount and a model are chosen. Credit is drawn directly from the key by OpenRouter as each run is carried out. Any part of a donation left unspent is not charged.</p>

		<h2>What a run does</h2>
		<p>Each run takes one open question, searches the web and writes a report. The findings for the project are then revised to include it, and a list of further questions is drawn up for the next run. Reports and findings are committed to the repository as text and as HTML, and every commit records the donor, the model, the tokens used and the cost.</p>
		<p>A donation is closed when it has been spent, when no open questions remain, or after 40 runs.</p>

		<h2>API keys</h2>
		<p>A new key should be created for this site, with a credit limit that would be acceptable to lose. Keys are checked with OpenRouter when they are added and are encrypted when stored. A key is used only for donations made from the account that added it, and it may be removed at any time from the account page.</p>
		<p>The amount chosen for a donation is enforced by this site. The credit limit on the key is enforced by OpenRouter, and it is the only protection that does not depend on this site.</p>

		<h2>Amounts and leaderboards</h2>
		<p>An amount is shown as raised once it has actually been spent on a completed run, at the figure reported by OpenRouter. Until then it is shown as pledged, and it is not counted on the leaderboards. Any part of a pledge that goes unused is never charged.</p>
		<p>Each project shows its progress towards the next milestone: $1, $5, $25, $100, $500 and so on. Milestones are round figures that indicate progress. They have no effect on how a donation is spent, and nothing is withheld until one is reached.</p>

		<h2>Reliability</h2>
		<p>All findings are generated by AI models and have not been independently reviewed. Sources should be consulted before any finding is relied upon. The contents of prompts and findings do not represent the views of this site.</p>

		<h2>Reports and removal</h2>
		<p>Prompts are not reviewed before they are published. Anyone may report a project with the link on its page, and reports are read by the operator of this site. A project is removed if it is unlawful, or if it exposes or targets a private person. The <a href="/terms">terms</a> and the <a href="/privacy">privacy notice</a> give further detail.</p>
	</div>
