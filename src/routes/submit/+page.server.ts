import { fail, redirect } from '@sveltejs/kit';
import { randomBytes } from 'node:crypto';
import { checkPrompt, slugFromPrompt, titleFromPrompt } from '#lib/prompt.ts';
import { run } from '#lib/server/db.ts';
import { config } from '#lib/server/env.ts';
import { HOUR, hit } from '#lib/server/limits.ts';
import { createRepo } from '#lib/server/repo.ts';
import type { Actions } from './$types';

function readme(title: string, prompt: string, handle: string) {
	const quoted = prompt
		.split('\n')
		.map((line) => `> ${line}`)
		.join('\n');
	return `# ${title}

This repository holds a research project from OpenResearch. It was submitted by @${handle}.

${quoted}

- \`PROMPT.md\` holds the prompt as it was submitted.
- \`findings.md\` and \`findings.html\` hold the current findings.
- \`open-questions.md\` lists what is to be examined next.
- \`runs/\` holds every run, as text and as HTML. Each commit records the donor, the model, the tokens and the cost.

The contents were generated by AI models and have not been independently reviewed.
`;
}

export const actions: Actions = {
	default: async ({ request, locals }) => {
		if (!locals.user) return fail(401, { message: 'An X account must be connected first.', prompt: '' });
		const form = await request.formData();
		const raw = form.get('prompt');
		const checked = checkPrompt(raw);
		if (!checked.ok) return fail(400, { message: checked.message, prompt: String(raw ?? '') });

		const { prompt } = checked;
		if (hit(`submit:${locals.user.id}`, config.promptsPerHour, HOUR)) {
			return fail(429, {
				message: `No more than ${config.promptsPerHour} prompts may be submitted in an hour from one account. The prompt has been kept on this page.`,
				prompt
			});
		}
		const title = titleFromPrompt(prompt);
		const slug = slugFromPrompt(prompt, randomBytes(3).toString('hex'));
		const user = locals.user;
		await createRepo(
			slug,
			{
				'PROMPT.md': `${prompt}\n`,
				'README.md': readme(title, prompt, user.handle),
				'open-questions.md': '# Open questions\n\nNone are listed at present.\n'
			},
			`Prompt submitted by @${user.handle}`,
			{ name: `@${user.handle}`, email: `${user.x_id}@x.openresearch.invalid` }
		);
		run(
			`INSERT INTO projects (slug, title, prompt, author_id, created_at) VALUES (?, ?, ?, ?, ?)`,
			slug,
			title,
			prompt,
			user.id,
			Date.now()
		);
		redirect(303, `/p/${slug}?submitted=1`);
	}
};
